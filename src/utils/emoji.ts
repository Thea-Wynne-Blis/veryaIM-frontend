const RECENT_KEY = 'veryal.recentEmojis'
const RECENT_LIMIT = 20

/** 读取最近使用；隐私模式或数据损坏时返回空列表。 */
export function loadRecentEmojis(): string[] {
  try {
    const raw = window.localStorage.getItem(RECENT_KEY)
    const parsed: unknown = raw ? JSON.parse(raw) : []
    if (!Array.isArray(parsed)) return []
    return parsed
      .filter((item): item is string => typeof item === 'string' && item.length > 0)
      .slice(0, RECENT_LIMIT)
  } catch {
    return []
  }
}

/** 记录一次使用：去重后放到最前，最多保留 {@link RECENT_LIMIT} 个。 */
export function rememberEmoji(emoji: string): string[] {
  const next = [emoji, ...loadRecentEmojis().filter((item) => item !== emoji)]
    .slice(0, RECENT_LIMIT)
  try {
    window.localStorage.setItem(RECENT_KEY, JSON.stringify(next))
  } catch {
    // localStorage 不可写时只影响「最近使用」，表情本身照常可用
  }
  return next
}
